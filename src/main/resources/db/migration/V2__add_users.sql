CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(254) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    display_name   VARCHAR(80)  NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

-- Every application now belongs to a user. This intentionally fails if
-- unowned rows exist, rather than silently deleting or misattributing them.
ALTER TABLE job_applications ADD COLUMN user_id BIGINT NOT NULL;
ALTER TABLE job_applications
    ADD CONSTRAINT fk_job_applications_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;

-- Queries are always scoped by user, usually filtered by status.
DROP INDEX idx_job_applications_status;
CREATE INDEX idx_job_applications_user_status ON job_applications (user_id, status);
